# Normalise a few characters to glyphs we carry.
ALIASES = {
    "’": "'",
    "‘": "'",
    "“": '"',
    "”": '"',
    "—": "-",
    "–": "-",
}


def glyph(ch):
    ch = ALIASES.get(ch, ch)
    return GLYPHS.get(ch.upper(), GLYPHS["?"])


def text_width(text, scale):
    """Pixel width of text at the given scale (no trailing space)."""
    if not text:
        return 0
    return len(text) * 6 * scale - scale


def wrap(text, max_width, scale):
    """Split text into lines that fit max_width pixels at scale."""
    words = text.split(" ")
    lines = []
    cur = ""
    for word in words:
        trial = word if not cur else cur + " " + word
        if text_width(trial, scale) <= max_width or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines
